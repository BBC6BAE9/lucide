#!/usr/bin/env python3
"""Regenerates the Swift, Kotlin and ArkTS LucideName catalogs from a lucide-static release.

Usage: Scripts/generate-names.py 1.70.0

Canonical icons come from the release's tags.json. Every other SVG in icons/ is a renamed
icon kept for compatibility; it becomes a deprecated alias of the canonical icon with the
same drawing.
"""

import io
import json
import re
import sys
import tarfile
import urllib.request
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent.parent / "Sources/LucideRemote/LucideName.swift"
KOTLIN_OUTPUT = OUTPUT.parents[2] / "android/src/main/kotlin/dev/lucideremote/LucideName.kt"
ARKTS_OUTPUT = OUTPUT.parents[2] / "harmony/lucide_remote/src/main/ets/LucideName.ets"

SWIFT_KEYWORDS = {
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func", "import", "init",
    "inout", "internal", "let", "open", "operator", "private", "precedencegroup", "protocol", "public",
    "rethrows", "static", "struct", "subscript", "typealias", "var", "break", "case", "catch", "continue",
    "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in", "repeat", "return",
    "throw", "switch", "where", "while", "as", "any", "false", "is", "nil", "self", "super", "throws",
    "true", "try", "await", "consume", "copy", "discard", "borrowing", "consuming", "Type", "Self",
}
NAME = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def identifier(name: str) -> str:
    first, *rest = name.split("-")
    result = first + "".join(part[:1].upper() + part[1:] for part in rest)
    if result[0].isdigit():
        result = "_" + result
    return f"`{result}`" if result in SWIFT_KEYWORDS else result


def drawing(svg: str) -> str:
    return re.sub(r'class="[^"]*"|<!--.*?-->|\s+', "", svg, flags=re.S)


def write_kotlin(version: str, tags: list[str], aliases: list[tuple[str, str]]) -> None:
    def kotlin(name: str) -> str:
        # Quoting is transparent at the call site except for Kotlin keywords.
        return "`" + identifier(name).strip("`") + "`"

    lines = [
        f"// Generated by Scripts/generate-names.py from lucide-static {version}. Do not edit.",
        "package dev.lucideremote",
        "",
        '@Suppress("EnumEntryName")',
        "enum class LucideName(val rawValue: String) {",
    ]
    lines += [f'    {kotlin(name)}("{name}"),' for name in tags]
    lines += [
        "    ;",
        "",
        "    companion object {",
        f'        const val version = "{version}"',
        "        val allCases: List<LucideName> get() = entries",
        "        private val byRawValue by lazy { entries.associateBy(LucideName::rawValue) }",
        "",
        "        fun fromRawValue(rawValue: String): LucideName? = byRawValue[rawValue]",
    ]
    for alias, target in aliases:
        lines += [
            "",
            f'        @Deprecated("Renamed to {identifier(target).strip("`")}", ReplaceWith("LucideName.{kotlin(target)}"))',
            f"        val {kotlin(alias)}: LucideName get() = {kotlin(target)}",
        ]
    lines += ["    }", "}", ""]
    KOTLIN_OUTPUT.write_text("\n".join(lines))


def write_arkts(version: str, tags: list[str], aliases: list[tuple[str, str]]) -> None:
    def arkts(name: str) -> str:
        return identifier(name).strip("`")

    lines = [
        f"// Generated by Scripts/generate-names.py from lucide-static {version}. Do not edit.",
        "",
        "export class LucideName {",
        f"  static readonly version: string = '{version}';",
        "",
    ]
    lines += [f"  static readonly {arkts(name)}: LucideName = new LucideName('{name}');" for name in tags]
    for alias, target in aliases:
        lines += [
            "",
            f"  /** @deprecated Use LucideName.{arkts(target)}. */",
            f"  static get {arkts(alias)}(): LucideName {{ return LucideName.{arkts(target)}; }}",
        ]
    lines += [
        "",
        "  private static readonly byRawValue: Map<string, LucideName> = LucideName.makeIndex();",
        "",
        "  readonly rawValue: string;",
        "",
        "  private constructor(rawValue: string) {",
        "    this.rawValue = rawValue;",
        "  }",
        "",
        "  static get allCases(): LucideName[] {",
        "    return Array.from(LucideName.byRawValue.values());",
        "  }",
        "",
        "  static fromRawValue(rawValue: string): LucideName | undefined {",
        "    return LucideName.byRawValue.get(rawValue);",
        "  }",
        "",
        "  private static makeIndex(): Map<string, LucideName> {",
        "    const names: LucideName[] = [",
    ]
    lines += [f"      LucideName.{arkts(name)}," for name in tags]
    lines += [
        "    ];",
        "    const index = new Map<string, LucideName>();",
        "    for (const name of names) {",
        "      index.set(name.rawValue, name);",
        "    }",
        "    return index;",
        "  }",
        "}",
        "",
    ]
    ARKTS_OUTPUT.write_text("\n".join(lines))


def main() -> None:
    if len(sys.argv) != 2 or not re.fullmatch(r"\d+\.\d+\.\d+", sys.argv[1]):
        sys.exit(__doc__)
    version = sys.argv[1]
    url = f"https://registry.npmjs.org/lucide-static/-/lucide-static-{version}.tgz"
    with urllib.request.urlopen(url) as response:
        archive = tarfile.open(fileobj=io.BytesIO(response.read()), mode="r:gz")

    icons: dict[str, str] = {}
    tags: list[str] = []
    for member in archive.getmembers():
        if member.name == "package/tags.json":
            tags = sorted(json.load(archive.extractfile(member)))
        elif member.name.startswith("package/icons/") and member.name.endswith(".svg"):
            icons[member.name[len("package/icons/"):-4]] = archive.extractfile(member).read().decode()

    canonical = set(tags)
    if not tags or not canonical <= icons.keys():
        sys.exit("tags.json is missing or names icons that are not in icons/")
    for name in icons:
        if not NAME.fullmatch(name):
            sys.exit(f"unexpected icon name: {name}")

    by_drawing: dict[str, list[str]] = {}
    for name in tags:
        by_drawing.setdefault(drawing(icons[name]), []).append(name)
    aliases: list[tuple[str, str]] = []
    for name in sorted(icons.keys() - canonical):
        targets = by_drawing.get(drawing(icons[name]), [])
        if len(targets) != 1:
            sys.exit(f"alias {name} matches {targets or 'no'} canonical icons")
        # `arrow-down-01` and `arrow-down-0-1` are both `arrowDown01`; the case already covers it.
        if identifier(name) != identifier(targets[0]):
            aliases.append((name, targets[0]))

    identifiers = [identifier(name) for name in tags] + [identifier(alias) for alias, _ in aliases]
    if len(set(identifiers)) != len(identifiers):
        sys.exit("two icon names map to the same Swift identifier")

    lines = [
        f"// Generated by Scripts/generate-names.py from lucide-static {version}. Do not edit.",
        "",
        "/// Every icon in the pinned Lucide release. The raw value is the name shown on lucide.dev.",
        "public enum LucideName: String, CaseIterable, Sendable {",
        f'  public static let version = "{version}"',
        "",
    ]
    lines += [f'  case {identifier(name)} = "{name}"' for name in tags]
    lines += ["}", "", "extension LucideName {"]
    for alias, target in aliases:
        lines.append(f'  @available(*, deprecated, renamed: "{identifier(target).strip("`")}")')
        lines.append(f"  public static var {identifier(alias)}: LucideName {{ .{identifier(target)} }}")
    lines += ["}", ""]
    OUTPUT.write_text("\n".join(lines))
    write_kotlin(version, tags, aliases)
    write_arkts(version, tags, aliases)
    print(f"{OUTPUT.name}: {len(tags)} icons, {len(aliases)} deprecated aliases")


if __name__ == "__main__":
    main()
